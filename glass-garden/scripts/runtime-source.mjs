import {readFile,writeFile} from 'node:fs/promises';import {createHash} from 'node:crypto';import {fileURLToPath} from 'node:url';
const source=new URL('../web/game/src/game.js',import.meta.url),target=new URL('../web/game-runtime.js',import.meta.url);
export async function runtimeSource(){
 let code=await readFile(source,'utf8');
 if(createHash('sha256').update(code).digest('hex')!=='b32fda93afbc29181308ed149992da0b5c35b5908edb3e7733dfe1ac0b13b9fb')throw Error('Unknown original game source');
 for(const [before,after] of [
  ['loadLevel:function(index,restore=false){','loadLevel:function(index,restore=false,activeLevel=LEVELS[index]){'],
  ['P.restore(LEVELS[index],restore?','P.restore(activeLevel,restore?'],
  ['this.layout=R.layoutFor(LEVELS[index]);','this.layout=R.layoutFor(activeLevel);']
 ]){if(code.split(before).length!==2)throw Error('Unknown scene integration point');code=code.replace(before,after);}
 return '// Generated by scripts/runtime-source.mjs; original source remains read-only.\n'+code;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){const code=await runtimeSource();if(process.argv.includes('--write'))await writeFile(target,code);else if(await readFile(target,'utf8')!==code)throw Error('Runtime scene adapter drift');}
